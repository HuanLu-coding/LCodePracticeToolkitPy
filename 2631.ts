// https://leetcode.com/problems/group-by/

// # # GroupBy Array 问题分析与解决方案
//
// ## 问题评估
//
// 这个问题是关于为JavaScript/TypeScript的Array对象实现一个`groupBy`方法，该方法接收一个函数作为参数，该函数将数组中的每个元素映射到一个字符串键，然后根据这些键将元素分组为一个对象。
//
// ### 问题陈述分析
//
// 1. 我们需要扩展`Array`原型，添加`groupBy`方法
// 2. 该方法接受一个函数参数，该函数将数组元素映射到字符串键
// 3. 返回值是一个对象，其中键是映射函数生成的字符串，值是原始数组中映射到该键的所有元素组成的数组
//
// ### 边缘情况和约束条件
//
// 1. 空数组
// 2. 映射函数返回重复键的情况
// 3. 映射函数返回非字符串值的可能性(根据接口定义，函数应返回字符串)
// 4. 数组中包含不同类型元素的情况
//
// ## 解决方案探索
//
// ### 解决方案1: 使用对象累加器
//
// 这是一个直接的解决方案，我们遍历数组，对每个元素应用映射函数获取键，然后将元素添加到相应的组中。
//
// ```typescript
Array.prototype.groupBy = function <T>(fn: (item: T) => string): Record<string, T[]> {
    const result: Record<string, T[]> = {};

    for (const item of this) {
        // 获取当前元素的键
        const key = fn(item);

        // 如果键不存在，创建一个新数组
        if (!result[key]) {
            result[key] = [];
        }

        // 将当前元素添加到对应键的数组中
        result[key].push(item);
    }

    return result;
};
// ```
//
// #### 执行跟踪
//
// 以示例`[1,2,3].groupBy(String)`为例:
//
// 1. 初始化`result = {}`
// 2. 遍历数组`[1,2,3]`:
//    - 对元素`1`应用`String`函数，得到键`"1"`
//    - `result`中不存在键`"1"`，创建`result["1"] = []`
//    - 将`1`添加到`result["1"]`，现在`result = {"1": [1]}`
//    - 对元素`2`应用`String`函数，得到键`"2"`
//    - `result`中不存在键`"2"`，创建`result["2"] = []`
//    - 将`2`添加到`result["2"]`，现在`result = {"1": [1], "2": [2]}`
//    - 对元素`3`应用`String`函数，得到键`"3"`
//    - `result`中不存在键`"3"`，创建`result["3"] = []`
//    - 将`3`添加到`result["3"]`，现在`result = {"1": [1], "2": [2], "3": [3]}`
// 3. 返回`result`
//
// #### 边缘情况验证
//
// 1. 空数组: `[].groupBy(String)` 会返回空对象 `{}`
// 2. 重复键: `[1, 1, 2].groupBy(String)` 会返回 `{"1": [1, 1], "2": [2]}`
// 3. 如果映射函数违反类型约束返回非字符串，TypeScript编译时会报错
//
// #### 复杂度分析
//
// - 时间复杂度: O(n)，其中n是数组长度，我们只遍历数组一次
// - 空间复杂度: O(n)，最坏情况下每个元素映射到不同的键
//
// #### 优缺点
//
// 优点:
// - 简单直观，容易理解
// - 时间和空间复杂度都是最优的
//
// 缺点:
// - 没有特别的缺点，这是一个相对标准的实现方式
//
// ### 解决方案2: 使用Map结构后转换为对象
//
// 利用Map可能在某些情况下有更好的性能特性。
//
// ```typescript
Array.prototype.groupBy = function <T>(fn: (item: T) => string): Record<string, T[]> {
    const map = new Map<string, T[]>();

    for (const item of this) {
        const key = fn(item);

        if (!map.has(key)) {
            map.set(key, []);
        }

        map.get(key)!.push(item);
    }

    // 将Map转换为普通对象
    const result: Record<string, T[]> = {};
    for (const [key, value] of map.entries()) {
        result[key] = value;
    }

    return result;
};
// ```
//
// #### 执行跟踪
//
// 以示例`[1,2,3].groupBy(String)`为例:
//
// 1. 初始化`map = new Map()`
// 2. 遍历数组`[1,2,3]`:
//    - 对元素`1`应用`String`函数，得到键`"1"`
//    - `map`中不存在键`"1"`，创建`map.set("1", [])`
//    - 将`1`添加到`map.get("1")`，现在`map = {"1" => [1]}`
//    - 对元素`2`应用`String`函数，得到键`"2"`
//    - `map`中不存在键`"2"`，创建`map.set("2", [])`
//    - 将`2`添加到`map.get("2")`，现在`map = {"1" => [1], "2" => [2]}`
//    - 对元素`3`应用`String`函数，得到键`"3"`
//    - `map`中不存在键`"3"`，创建`map.set("3", [])`
//    - 将`3`添加到`map.get("3")`，现在`map = {"1" => [1], "2" => [2], "3" => [3]}`
// 3. 将`map`转换为普通对象`result`
// 4. 返回`result = {"1": [1], "2": [2], "3": [3]}`
//
// #### 边缘情况验证
//
// 与解决方案1相同
//
// #### 复杂度分析
//
// - 时间复杂度: O(n)，遍历数组一次，然后遍历Map一次
// - 空间复杂度: O(n)，需要存储Map和结果对象
//
// #### 优缺点
//
// 优点:
// - Map对于键的操作可能在某些JavaScript引擎中更高效
// - 对于大量数据或频繁查找的场景可能有优势
//
// 缺点:
// - 需要额外的一步将Map转换为普通对象
// - 代码比解决方案1略长
//
// ### 解决方案3: 使用reduce方法
//
// 利用数组的reduce方法可以使代码更加函数式和简洁。
//
// ```typescript
Array.prototype.groupBy = function <T>(fn: (item: T) => string): Record<string, T[]> {
    return this.reduce((result: Record<string, T[]>, item: T) => {
        const key = fn(item);

        if (!result[key]) {
            result[key] = [];
        }

        result[key].push(item);
        return result;
    }, {});
};
// ```
//
// #### 执行跟踪
//
// 以示例`[1,2,3].groupBy(String)`为例:
//
// 1. 初始化`result = {}`（reduce的初始累加器）
// 2. 对元素`1`应用reduce:
//    - 键`"1"` = String(1)
//    - `result`中不存在键`"1"`，创建`result["1"] = []`
//    - 将`1`添加到`result["1"]`，现在`result = {"1": [1]}`
// 3. 对元素`2`应用reduce:
//    - 键`"2"` = String(2)
//    - `result`中不存在键`"2"`，创建`result["2"] = []`
//    - 将`2`添加到`result["2"]`，现在`result = {"1": [1], "2": [2]}`
// 4. 对元素`3`应用reduce:
//    - 键`"3"` = String(3)
//    - `result`中不存在键`"3"`，创建`result["3"] = []`
//    - 将`3`添加到`result["3"]`，现在`result = {"1": [1], "2": [2], "3": [3]}`
// 5. 返回最终的`result`
//
// #### 边缘情况验证
//
// 与解决方案1相同
//
// #### 复杂度分析
//
// - 时间复杂度: O(n)
// - 空间复杂度: O(n)
//
// #### 优缺点
//
// 优点:
// - 代码更加简洁，函数式风格
// - 不需要显式循环，逻辑更集中
//
// 缺点:
// - reduce函数对于不熟悉函数式编程的开发者可能不太直观
// - 在某些JavaScript引擎中，reduce可能比普通循环性能略低
//
// ## 解决方案比较
//
// | 评估标准 | 解决方案1 (对象累加器) | 解决方案2 (Map结构) | 解决方案3 (reduce方法) |
// |---------|-------------------|-----------------|-------------------|
// | 适合编码面试 | ✅ 简单直观 | ⚠️ 稍复杂 | ✅ 简洁专业 |
// | 时间复杂度 | O(n) | O(n) | O(n) |
// | 空间复杂度 | O(n) | O(n) | O(n) |
// | 代码可读性 | 很好 | 良好 | 很好（熟悉函数式编程的人） |
// | 边缘情况处理 | 完善 | 完善 | 完善 |

